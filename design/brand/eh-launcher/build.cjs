// Approved geometry is shared by the release and debug launcher assets.
// Run with --install to update Android resources as well as the design exports.
const fs = require('node:fs');
const path = require('node:path');
const sharp = require('sharp');
const source = require('../eh-link-tonal/build.cjs');
const OUT = __dirname;
const ROOT = path.resolve(OUT, '../../..');
const install = process.argv.includes('--install');
// Launchers display the central 72dp of the 108dp adaptive layers.
// At .18 the mark filled ~89% of that viewport despite fitting the safe zone.
// .145 leaves ~14% vertical breathing room on each side.
const ADAPTIVE_SCALE = .145;
const adaptiveOffset = scale => +(54 - 256 * scale).toFixed(3);
const adaptiveTransform = (scale = ADAPTIVE_SCALE) =>
  `translate(${adaptiveOffset(scale)} ${adaptiveOffset(scale)}) scale(${scale})`;
const palette = {
  '#FFD199':'#C4BEFF', '#FFAC66':'#9A8BF0', '#ED864A':'#6D60D0',
  '#F0A35D':'#A198EA', '#D98742':'#7968C9', '#B86A31':'#5142A0',
  '#FFFEFB':'#FDFBFF', '#F9F5EE':'#F1EEFA', '#EEE8DC':'#E2DBF0',
  '#42362C':'#363049', '#2C251F':'#262135', '#1D1814':'#191525',
  '#CA723C':'#5E50AB', '#9C5029':'#40327E', '#71522D':'#41345F',
  '#665636':'#4A3C68', '#5A3B28':'#392C54', '#A86737':'#63508E',
  '#C28A54':'#9280B1', '#FFF4DE':'#F3EEFF', '#D1C6AF':'#BEB3D1',
  '#65432E':'#4A3F6C',
};
const colorize = (s,debug) => debug ? s.replace(/#[0-9A-F]{6}/g,c=>palette[c] || c) : s;
function write(file,content) {
  fs.mkdirSync(path.dirname(file),{recursive:true});
  fs.writeFileSync(file,content);
}
const asset=(name,content)=>write(path.join(OUT,name),content);
const android=(variant,file,content)=>write(path.join(ROOT,'app/src',variant,'res',file),content);
const bitmapXml=`<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/brand/eh-launcher/build.cjs. -->
<bitmap xmlns:android="http://schemas.android.com/apk/res/android"
    android:src="@drawable/ic_launcher_art"
    android:gravity="fill"
    android:filter="true" />
`;
const adaptiveXml=`<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/brand/eh-launcher/build.cjs. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`;
const monoXml=`<?xml version="1.0" encoding="utf-8"?>
<!-- Generated from the approved vector geometry; shared by both build types. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <group android:scaleX="${ADAPTIVE_SCALE}" android:scaleY="${ADAPTIVE_SCALE}"
        android:translateX="${adaptiveOffset(ADAPTIVE_SCALE)}" android:translateY="${adaptiveOffset(ADAPTIVE_SCALE)}">
        <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd"
            android:pathData="${source.backing+source.windowPath}" />
    </group>
</vector>
`;
function backgroundXml(debug,night) {
  const start= colorize(night?'#42362C':'#FFFEFB',debug);
  const end= colorize(night?'#1D1814':'#EEE8DC',debug);
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/brand/eh-launcher/build.cjs. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0H108V108H0Z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="16.2" android:startY="0"
                android:endX="86.4" android:endY="108">
                <item android:offset="0" android:color="${start}" />
                <item android:offset="0.52" android:color="@color/ic_launcher_background" />
                <item android:offset="1" android:color="${end}" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
`;
}
function colorsXml(debug,night) {
  const color=colorize(night?'#2C251F':'#F9F5EE',debug);
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/brand/eh-launcher/build.cjs. -->
<resources>
    <color name="ic_launcher_background">${color}</color>
</resources>
`;
}
async function main() {
  const panels=[];
  for(const debug of [false,true]) {
    const label=debug?'debug':'release';
    const variant=debug?'debug':'main';
    for(const [suffix,dark,square] of [['icon',false,false],['dark',true,false],['square',false,true]]) {
      const svg=source.svg(colorize(source.icon(label+suffix,dark,square),debug));
      asset(`${label}-${suffix}.svg`,svg);
      await sharp(Buffer.from(svg)).resize(1024,1024).png().toFile(path.join(OUT,`${label}-${suffix}.png`));
    }
    const mark=source.svg(colorize(source.defs(label+'mark')+source.mark(label+'mark'),debug));
    asset(`${label}-mark.svg`,mark);
    await sharp(Buffer.from(mark)).resize(1024).png().toFile(path.join(OUT,`${label}-mark.png`));
    // The system supplies the outer mask and shadow for adaptive icons.
    // Keep local contact shadows, and omit the mark's outer ground shadow.
    const foreground=source.svg(colorize(source.defs(label+'fg')+`<g transform="${adaptiveTransform()}">${source.mark(label+'fg',false)}</g>`,debug),108,108);
    asset(`${label}-adaptive-foreground.svg`,foreground);
    const foregroundPng=await sharp(Buffer.from(foreground)).resize(432,432).png().toBuffer();
    asset(`${label}-adaptive-foreground.png`,foregroundPng);
    if(install) {
      android(variant,'drawable-xxxhdpi/ic_launcher_art.png',foregroundPng);
      for(const night of [false,true]) {
        android(variant,`drawable${night?'-night':''}/ic_launcher_background.xml`,backgroundXml(debug,night));
        android(variant,`values${night?'-night':''}/color_launcher.xml`,colorsXml(debug,night));
      }
      for(const [density,size] of [['mdpi',48],['hdpi',72],['xhdpi',96],['xxhdpi',144],['xxxhdpi',192]]) {
        const regular=await sharp(Buffer.from(source.svg(colorize(source.icon(label+'legacy'),debug)))).resize(size,size).webp({lossless:true}).toBuffer();
        android(variant,`mipmap-${density}/ic_launcher.webp`,regular);
        const circle=Buffer.from(source.svg(`<circle cx="256" cy="256" r="256" fill="white"/>`));
        const round=await sharp(Buffer.from(source.svg(colorize(source.icon(label+'round',false,true),debug)))).resize(size,size)
          .composite([{input:await sharp(circle).resize(size,size).png().toBuffer(),blend:'dest-in'}]).webp({lossless:true}).toBuffer();
        android(variant,`mipmap-${density}/ic_launcher_round.webp`,round);
      }
      for(const night of [false,true]) {
        const webp=await sharp(Buffer.from(source.svg(colorize(source.icon(label+'store'+night,night,true),debug)))).resize(512,512).webp({lossless:true}).toBuffer();
        write(path.join(ROOT,'app/src',variant,night?'ic_launcher_night-playstore.webp':'ic_launcher-playstore.webp'),webp);
      }
    }
    panels.push({debug,label});
  }
  if(install) {
    android('main','drawable/ic_launcher_foreground.xml',bitmapXml);
    android('main','drawable/ic_launcher_monochrome.xml',monoXml);
    android('main','mipmap-anydpi/ic_launcher.xml',adaptiveXml);
    android('main','mipmap-anydpi/ic_launcher_round.xml',adaptiveXml);
  }
  const text=(x,y,s,size=22,color='#665F72')=>`<text x="${x}" y="${y}" font-family="Microsoft YaHei, sans-serif" font-size="${size}" fill="${color}">${s}</text>`;
  let board=`<rect width="1200" height="900" fill="#EFEAF0"/>`+text(64,76,'EH / RELEASE + DEBUG',36,'#40384B');
  for(const {debug,label} of panels) {
    const x=debug?650:70;
    board+=`<g transform="translate(${x} 140) scale(.9375)">${colorize(source.icon('board'+label),debug)}</g>`;
    board+=text(x+8,670,debug?'DEBUG / 蓝紫色':'RELEASE / 杏橙色',24,'#40384B');
    for(const [i,size] of [48,72,96].entries()) {
      board+=`<g transform="translate(${x+8+i*132} ${716+(96-size)/2}) scale(${size/512})">${colorize(source.icon('small'+label+size),debug)}</g>`;
      board+=text(x+8+i*132,854,size+' px',15);
    }
  }
  asset('release-debug-board.svg',source.svg(board,1200,900));
  await sharp(Buffer.from(source.svg(board,1200,900))).png().toFile(path.join(OUT,'release-debug-board.png'));
  // Adaptive previews simulate the 108dp layers displayed in a 72dp viewport.
  let masks=`<rect width="1200" height="490" fill="#EFEAF0"/>`+text(44,52,'Android / 自适应裁切预览',26,'#40384B');
  for(const {debug,label} of panels) for(const [index,shape] of ['circle','square'].entries()) {
    const x=40+(debug?600:0)+index*280,y=90,id='mask'+label+shape;
    masks+=`<defs><clipPath id="${id}">${shape==='circle'?'<circle cx="128" cy="128" r="128"/>':'<rect width="256" height="256" rx="58"/>'}</clipPath></defs>`;
    const layers=source.defs(id)+`<rect width="108" height="108" fill="url(#${id}-tile)"/><g transform="${adaptiveTransform()}">${source.mark(id,false)}</g>`;
    masks+=`<g transform="translate(${x} ${y})"><g clip-path="url(#${id})"><g transform="translate(-64 -64) scale(${384/108})">${colorize(layers,debug)}</g></g></g>`;
    masks+=text(x+24,395,(debug?'Debug':'Release')+' / '+(shape==='circle'?'圆形':'圆角'),18);
  }
  asset('adaptive-mask-preview.svg',source.svg(masks,1200,490));
  await sharp(Buffer.from(source.svg(masks,1200,490))).png().toFile(path.join(OUT,'adaptive-mask-preview.png'));
  let spacing=`<rect width="1040" height="690" fill="#EFEAF0"/>`+text(60,72,'Android / 桌面边距优化',32,'#40384B');
  for(const [i,scale] of [.18,ADAPTIVE_SCALE].entries()) {
    const x=64+i*528,id='spacing'+i;
    const layers=source.defs(id,true)+`<rect width="108" height="108" fill="url(#${id}-tile)"/><g transform="${adaptiveTransform(scale)}">${source.mark(id,false)}</g>`;
    spacing+=`<defs><clipPath id="${id}-frame"><rect width="384" height="384" rx="86"/></clipPath></defs>`;
    spacing+=`<g transform="translate(${x} 148)"><g clip-path="url(#${id}-frame)"><g transform="translate(-96 -96) scale(${576/108})">${colorize(layers,true)}</g></g></g>`;
    spacing+=text(x,594,i?'调整后 / 主体约占 71% 高度':'调整前 / 主体约占 89% 高度',21,'#40384B');
  }
  spacing+=text(64,652,'正式、Debug、单色主题图标统一调整，图标背景保持满幅。',19);
  asset('adaptive-spacing-preview.svg',source.svg(spacing,1040,690));
  await sharp(Buffer.from(source.svg(spacing,1040,690))).png().toFile(path.join(OUT,'adaptive-spacing-preview.png'));
  console.log('Generated release/debug design assets'+(install?' and Android resource overlays.':'.'));
}
main().catch(e=>{console.error(e);process.exitCode=1;});
